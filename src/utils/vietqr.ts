export function formatTLV(tag: string, value: string): string {
  if (!value) return '';
  const len = value.length.toString().padStart(2, '0');
  return `${tag}${len}${value}`;
}

export function calculateCRC16(payload: string): string {
  let crc = 0xffff;
  for (let i = 0; i < payload.length; i++) {
    const code = payload.charCodeAt(i);
    crc ^= code << 8;
    for (let j = 0; j < 8; j++) {
      if ((crc & 0x8000) !== 0) {
        crc = (crc << 1) ^ 0x1021;
      } else {
        crc = crc << 1;
      }
      crc &= 0xffff;
    }
  }
  return crc.toString(16).toUpperCase().padStart(4, '0');
}

export function removeVietnameseAccents(str: string): string {
  return str
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/đ/g, 'd')
    .replace(/Đ/g, 'D')
    .trim();
}

export function buildVietQRPayload(
  bankBin: string,
  accountNo: string,
  accountName: string,
  amount?: string | number,
  description?: string
): string {
  if (!bankBin || !accountNo) return '';

  const cleanAccNo = accountNo.trim().replace(/\s+/g, '');
  const cleanAccName = removeVietnameseAccents(accountName || '').toUpperCase();
  const cleanDesc = removeVietnameseAccents(description || '');
  const numAmount = amount ? Number(amount) : 0;

  // Tag 38: Consumer Account Information (Napas standard)
  const napasGuid = formatTLV('00', 'A000000727');
  const bankBinTLV = formatTLV('00', bankBin);
  const accNoTLV = formatTLV('01', cleanAccNo);
  const beneficiaryInfo = formatTLV('01', `${bankBinTLV}${accNoTLV}`);
  const serviceCode = formatTLV('02', 'QRIBFTTA'); // Instant Interbank Transfer
  const tag38Value = `${napasGuid}${beneficiaryInfo}${serviceCode}`;
  const tag38 = formatTLV('38', tag38Value);

  // Tag 00: Payload Format Indicator ("01")
  const tag00 = formatTLV('00', '01');

  // Tag 01: Point of Initiation Method: 11 = Static, 12 = Dynamic
  const tag01 = formatTLV('01', numAmount > 0 ? '12' : '11');

  // Tag 53: Currency (704 = VND)
  const tag53 = formatTLV('53', '704');

  // Tag 54: Transaction Amount
  const tag54 = numAmount > 0 ? formatTLV('54', numAmount.toString()) : '';

  // Tag 58: Country Code ("VN")
  const tag58 = formatTLV('58', 'VN');

  // Tag 59: Beneficiary Name
  const tag59 = cleanAccName ? formatTLV('59', cleanAccName.slice(0, 25)) : '';

  // Tag 60: Merchant City
  const tag60 = formatTLV('60', 'VN');

  // Tag 62: Additional Data Field (Order / Description)
  let tag62 = '';
  if (cleanDesc) {
    const subtag08 = formatTLV('08', cleanDesc.slice(0, 25));
    tag62 = formatTLV('62', subtag08);
  }

  // Pre-CRC string ending with "6304"
  const preCrc = `${tag00}${tag01}${tag38}${tag53}${tag54}${tag58}${tag59}${tag60}${tag62}6304`;
  const checksum = calculateCRC16(preCrc);

  return `${preCrc}${checksum}`;
}
